export const DOCS = "apps/www/config/docs.ts";
export const REGISTRY_UI = "apps/www/registry/registry-ui.ts";
export const REGISTRY_EXAMPLES = "apps/www/registry/registry-examples.ts";
export const shared = [DOCS, REGISTRY_UI, REGISTRY_EXAMPLES];

// Every path `pnpm build:registry` may write (lefthook stages the same set).
export const generated = [
  "registry.json",
  "apps/www/registry.json",
  "apps/www/registry/__index__.tsx",
  "apps/www/public/registry.json",
  "apps/www/public/r/",
  "apps/www/public/llms.txt",
  "apps/www/public/llms-full.txt",
];
export const isGenerated = (path: string) =>
  generated.some((p) => (p.endsWith("/") ? path.startsWith(p) : path === p));
const aggregate = [
  ...generated.filter((path) => !path.endsWith("/")),
  "apps/www/public/r/registry.json",
  "apps/www/public/r/index.json",
];

const literal = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const demoName = (slug: string) => `${literal(slug)}-demo[a-z0-9-]*`;

export type Kind =
  | "component"
  | "demo"
  | "docs"
  | "shared"
  | "generated"
  | "unexpected"
  | "unrelated";

/**
 * The exact packaged file set. Anything else that contains the slug is
 * "unexpected" and stops the run; everything else is "unrelated" and never
 * travels.
 */
export function classify(path: string, slug: string): Kind {
  if (path === `apps/www/registry/magicui/${slug}.tsx`) return "component";
  if (new RegExp(`^apps/www/registry/example/${demoName(slug)}\\.tsx$`).test(path))
    return "demo";
  if (path === `apps/www/content/docs/components/${slug}.mdx`) return "docs";
  if (shared.includes(path)) return "shared";
  if (ownGenerated(path, slug)) return "generated";
  return path.includes(slug) ? "unexpected" : "unrelated";
}
/** Generated artifacts the slug's registration may change. */
export function ownGenerated(path: string, slug: string): boolean {
  return (
    aggregate.includes(path) ||
    new RegExp(
      `^apps/www/public/r/${literal(slug)}(?:-demo[a-z0-9-]*)?\\.json$`,
    ).test(path)
  );
}
export const isCandidate = (kind: Kind) =>
  kind === "component" || kind === "demo" || kind === "docs";
const isSource = (kind: Kind) => isCandidate(kind) || kind === "shared";

export function unexpected(paths: string[], slug: string, where: string) {
  const found = paths.filter((path) => classify(path, slug) === "unexpected");
  if (found.length)
    throw new Error(
      [
        `Unexpected changed path(s) containing "${slug}" in ${where}:`,
        ...found.map((path) => `- ${path}`),
        `Only apps/www/registry/magicui/${slug}.tsx, apps/www/registry/example/${slug}-demo*.tsx,`,
        `apps/www/content/docs/components/${slug}.mdx, the slug's registry and sidebar entries`,
        "and the artifacts regenerated by pnpm build:registry can be packaged.",
      ].join("\n"),
    );
}

export interface File {
  bytes: Buffer;
  mode: string;
}
export type Files = Map<string, File>;

export async function tree(
  git: Commands,
  cwd: string,
  ref: string,
  slug: string,
): Promise<Files> {
  const files: Files = new Map();
  const listing = (await git.git(cwd, ["ls-tree", "-rz", ref])).toString();
  for (const entry of listing.split("\0").filter(Boolean)) {
    const match = /^(\d+) blob ([a-f0-9]+)\t([\s\S]+)$/.exec(entry);
    if (!match) continue;
    const mode = match[1]!;
    const oid = match[2]!;
    const path = match[3]!;
    if (!isSource(classify(path, slug))) continue;
    if (mode !== "100644" && mode !== "100755")
      throw new Error(`Unsupported candidate file mode: ${path} (${mode})`);
    files.set(path, {
      bytes: await git.git(cwd, ["cat-file", "blob", oid]),
      mode,
    });
  }
  return files;
}

// Git quotes paths with C escapes (including octal UTF-8 bytes).
function unquote(value: string): string {
  if (!value.startsWith('"')) return value;
  const bytes: number[] = [];
  const body = value.slice(1, -1);
  for (let i = 0; i < body.length; i++) {
    const char = body[i]!;
    if (char !== "\\") bytes.push(...Buffer.from(char));
    else {
      const octal = /^[0-7]{1,3}/.exec(body.slice(i + 1))?.[0];
      if (octal) {
        bytes.push(Number.parseInt(octal, 8));
        i += octal.length;
      } else {
        const escaped = body[++i]!;
        bytes.push(
          ...Buffer.from(
            ({ n: "\n", t: "\t", r: "\r" } as Record<string, string>)[
              escaped
            ] ?? escaped,
          ),
        );
      }
    }
  }
  return Buffer.from(bytes).toString();
}

function binaryLiteral(section: string): Buffer {
  const match = /GIT binary patch\nliteral (\d+)\n([\s\S]*?)(?:\n\n|$)/.exec(
    section,
  );
  if (!match)
    throw new Error(
      "Binary delta snapshots are unsupported; use a literal binary patch",
    );
  const alphabet =
    "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz!#$%&()*+-;<=>?@^_`{|}~";
  const chunks: Buffer[] = [];
  for (const line of match[2]!.split("\n").filter(Boolean)) {
    const code = line.charCodeAt(0);
    const length = code <= 90 ? code - 64 : code - 70;
    if (length < 1 || length > 52)
      throw new Error("Invalid binary patch length");
    const decoded: number[] = [];
    for (let i = 1; i < line.length; i += 5) {
      let value = 0;
      for (const char of line.slice(i, i + 5)) {
        const digit = alphabet.indexOf(char);
        if (digit < 0) throw new Error("Invalid binary patch encoding");
        value = value * 85 + digit;
      }
      if (value > 0xffffffff) throw new Error("Invalid binary patch word");
      decoded.push(
        (value >>> 24) & 255,
        (value >>> 16) & 255,
        (value >>> 8) & 255,
        value & 255,
      );
    }
    chunks.push(Buffer.from(decoded.slice(0, length)));
  }
  const bytes = inflateSync(Buffer.concat(chunks));
  if (bytes.length !== Number(match[1]))
    throw new Error("Invalid binary patch size");
  return bytes;
}

function textPatch(before: Buffer, section: string): Buffer {
  const source = before.toString("utf8");
  if (!Buffer.from(source).equals(before))
    throw new Error("Non-UTF-8 text patch");
  const original = source.match(/[^\n]*\n|[^\n]+$/g) ?? [];
  const lines = section.match(/[^\n]*\n|[^\n]+$/g) ?? [];
  const result: string[] = [];
  let cursor = 0;
  for (let i = 0; i < lines.length; i++) {
    const hunk = /^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@/.exec(lines[i]!);
    if (!hunk) continue;
    const count = Number(hunk[2] ?? 1);
    const start = Number(hunk[1]) - (count ? 1 : 0);
    if (start < cursor || start > original.length)
      throw new Error("Invalid snapshot hunk position");
    result.push(...original.slice(cursor, start));
    cursor = start;
    let removed = 0;
    let added = 0;
    while (i + 1 < lines.length && /^[ +\-\\]/.test(lines[i + 1]!)) {
      const line = lines[++i]!;
      const kind = line[0];
      if (kind === "\\") throw new Error("Misplaced snapshot newline marker");
      let text = line.slice(1);
      if (lines[i + 1]?.startsWith("\\ No newline")) {
        text = text.replace(/\n$/, "");
        i++;
      }
      if (kind !== "+") {
        if (original[cursor++] !== text)
          throw new Error("Snapshot does not match its base");
        removed++;
      }
      if (kind !== "-") {
        result.push(text);
        added++;
      }
    }
    if (removed !== count || added !== Number(hunk[4] ?? 1))
      throw new Error("Invalid snapshot hunk counts");
  }
  result.push(...original.slice(cursor));
  return Buffer.from(result.join(""));
}

/** Each before.patch is a complete diff against the candidate base, never a round delta. */
export async function snapshot(
  git: Commands,
  cwd: string,
  base: Files,
  patch: string,
  slug: string,
  where = "a snapshot",
): Promise<Files> {
  const result = new Map(base);
  const sections: { path: string; section: string }[] = [];
  for (const section of patch.split(/(?=^diff --git )/m).filter(Boolean)) {
    if (!section.startsWith("diff --git "))
      throw new Error("Invalid snapshot patch");
    const header = section.split("\n")[0]!.slice(11);
    const quoted = /^("(?:\\.|[^"\\])*") ("(?:\\.|[^"\\])*")$/.exec(header);
    const split =
      [...header.matchAll(/ b\//g)].find(
        (match) =>
          header.slice(2, match.index) === header.slice(match.index + 3),
      )?.index ?? -1;
    const oldPath = unquote(quoted?.[1] ?? header.slice(0, split)).slice(2);
    const path = unquote(quoted?.[2] ?? header.slice(split + 1)).slice(2);
    if (oldPath !== path || path.split("/").includes(".."))
      throw new Error(`Unsafe or renamed snapshot path: ${path}`);
    sections.push({ path, section });
  }
  unexpected(
    sections.map(({ path }) => path),
    slug,
    where,
  );
  for (const { path, section } of sections) {
    if (!isSource(classify(path, slug))) continue;
    if (/^deleted file mode /m.test(section)) {
      result.delete(path);
      continue;
    }
    const mode = /^new file mode (\d+)|^new mode (\d+)/m.exec(section);
    const fileMode = mode?.[1] ?? mode?.[2] ?? base.get(path)?.mode ?? "100644";
    if (!["100644", "100755"].includes(fileMode))
      throw new Error(`Unsafe snapshot mode: ${path}`);
    const oldOid = /^index ([a-f0-9]+)\.\./m.exec(section)?.[1];
    const before =
      oldOid && !/^0+$/.test(oldOid)
        ? await git.git(cwd, ["cat-file", "blob", oldOid])
        : (base.get(path)?.bytes ?? Buffer.alloc(0));
    const bytes = section.includes("\nGIT binary patch\n")
      ? binaryLiteral(section)
      : textPatch(before, section);
    const newOid = /^index [a-f0-9]+\.\.([a-f0-9]+)/m.exec(section)?.[1];
    if (
      newOid &&
      !["sha1", "sha256"].some((algorithm) =>
        createHash(algorithm)
          .update(`blob ${bytes.length}\0`)
          .update(bytes)
          .digest("hex")
          .startsWith(newOid),
      )
    )
      throw new Error(
        `Snapshot result does not match its Git object hash: ${path}`,
      );
    result.set(path, { bytes, mode: fileMode });
  }
  return result;
}

/** Paths that differ between `base` and the working tree, untracked included. */
export async function changedPaths(
  git: Commands,
  cwd: string,
  base: string,
): Promise<string[]> {
  const split = (value: Buffer) => value.toString().split("\0").filter(Boolean);
  return [
    ...new Set([
      ...split(
        await git.git(cwd, ["diff", "--name-only", "-z", "--no-renames", base]),
      ),
      ...split(
        await git.git(cwd, ["ls-files", "--others", "--exclude-standard", "-z"]),
      ),
    ]),
  ].sort();
}

/**
 * The working tree's candidate files and shared sources. Fails on any changed
 * path that contains the slug but is not part of the exact file set; returns
 * the other changed paths that are ignored.
 */
export async function finalFiles(
  git: Commands,
  cwd: string,
  base: string,
  slug: string,
): Promise<{ files: Files; ignored: string[] }> {
  const paths = await changedPaths(git, cwd, base);
  unexpected(paths, slug, cwd);
  const files: Files = new Map();
  for (const path of new Set([
    ...paths.filter((path) => isCandidate(classify(path, slug))),
    ...shared,
  ])) {
    try {
      const stat = await lstat(join(cwd, path));
      if (!stat.isFile())
        throw new Error(`Candidate must be a regular file: ${path}`);
      files.set(path, {
        bytes: await readFile(join(cwd, path)),
        mode: stat.mode & 0o111 ? "100755" : "100644",
      });
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
    }
  }
  return {
    files,
    ignored: paths.filter((path) => classify(path, slug) === "unrelated"),
  };
}

function identity(object: ts.ObjectLiteralExpression): string | undefined {
  for (const name of ["name", "title", "href"]) {
    const value = stringValue(property(object, name));
    if (value !== undefined) return `${name}=${JSON.stringify(value)}`;
  }
  return undefined;
}
const wrapper = (node: ts.Node) =>
  ts.isAsExpression(node) ||
  ts.isSatisfiesExpression(node) ||
  ts.isParenthesizedExpression(node) ||
  ts.isTypeAssertionExpression(node);
/**
 * A structural address such as `docsConfig.sidebarNav[title="Backgrounds"].items`.
 * Arrays are matched by this address (the category title), never by position
 * or by a neighbouring entry.
 */
export function arrayPath(array: ts.ArrayLiteralExpression): string {
  const parts: string[] = [];
  let current: ts.Node = array;
  for (;;) {
    while (current.parent && wrapper(current.parent)) current = current.parent;
    const parent = current.parent;
    if (parent && ts.isVariableDeclaration(parent)) {
      if (!ts.isIdentifier(parent.name))
        throw new Error("Unsupported destructured declaration");
      parts.unshift(parent.name.text);
      return parts.join("");
    }
    if (parent && ts.isExportAssignment(parent)) {
      parts.unshift("default");
      return parts.join("");
    }
    if (parent && ts.isPropertyAssignment(parent)) {
      const name = ts.isIdentifier(parent.name)
        ? parent.name.text
        : stringValue(parent.name);
      if (name === undefined) throw new Error("Unsupported computed property");
      parts.unshift(`.${name}`);
      current = parent.parent;
      continue;
    }
    if (
      parent &&
      ts.isArrayLiteralExpression(parent) &&
      ts.isObjectLiteralExpression(current)
    ) {
      const id = identity(current);
      if (!id)
        throw new Error("An enclosing object has no name, title or href");
      parts.unshift(`[${id}]`);
      current = parent;
      continue;
    }
    throw new Error(
      `Unsupported structure around a shared array (${parent ? ts.SyntaxKind[parent.kind] : "none"})`,
    );
  }
}
function arrays(source: string): ts.ArrayLiteralExpression[] {
  const found: ts.ArrayLiteralExpression[] = [];
  walk(parseTsx(source), (node) => {
    if (ts.isArrayLiteralExpression(node)) found.push(node);
  });
  return found;
}

function entries(source: string, path: string, slug: string) {
  const example = new RegExp(`^${demoName(slug)}$`);
  return objectLiterals(source).filter((object) => {
    if (!ts.isArrayLiteralExpression(object.parent)) return false;
    if (path === DOCS)
      return (
        stringValue(property(object, "href")) === `/docs/components/${slug}`
      );
    const name = stringValue(property(object, "name"));
    if (name === undefined) return false;
    return path === REGISTRY_UI ? name === slug : example.test(name);
  });
}
function bounds(source: string, object: ts.ObjectLiteralExpression) {
  const start = source.lastIndexOf("\n", object.getStart()) + 1;
  const end = /^,[ \t]*\r?\n/.exec(source.slice(object.end));
  if (!/^\s*$/.test(source.slice(start, object.getStart())) || !end)
    throw new Error(
      "Shared entries must occupy complete lines with a trailing comma",
    );
  return { start, end: object.end + end[0].length };
}
export function entryBytes(
  source: string,
  path: string,
  slug: string,
): string[] {
  return entries(source, path, slug).map((object) => {
    const range = bounds(source, object);
    return source.slice(range.start, range.end);
  });
}
const occurrences = (source: string, slug: string) =>
  source.split(slug).length - 1;

/**
 * Append only the slug's entries at the END of the matching upstream array:
 * `ui` / `examples` in the registries, the category (matched by title) in the
 * docs sidebar. Unrelated candidate edits never travel.
 */
export function projectShared(
  upstream: string,
  source: string,
  path: string,
  slug: string,
): string {
  if (entries(upstream, path, slug).length)
    throw new Error(`${path}: ${slug} already has entries upstream`);
  const incoming = entries(source, path, slug);
  let remainder = source;
  for (const object of [...incoming].reverse()) {
    const range = bounds(source, object);
    remainder = remainder.slice(0, range.start) + remainder.slice(range.end);
  }
  if (occurrences(remainder, slug) > occurrences(upstream, slug))
    throw new Error(
      `${path}: "${slug}" appears outside its own entries; only the entries are packaged`,
    );
  if (path === DOCS) {
    if (incoming.length > 1)
      throw new Error(`${path}: ${slug} has more than one sidebar entry`);
    for (const object of incoming)
      if (stringValue(property(object, "label")) !== "New")
        throw new Error(`${path}: the ${slug} sidebar entry needs label: "New"`);
  }
  const groups = new Map<string, string[]>();
  for (const object of incoming) {
    const target = arrayPath(object.parent as ts.ArrayLiteralExpression);
    const range = bounds(source, object);
    groups.set(target, [
      ...(groups.get(target) ?? []),
      source.slice(range.start, range.end),
    ]);
  }
  let result = upstream;
  for (const [target, texts] of groups) {
    const matches = arrays(result).filter((array) => {
      try {
        return arrayPath(array) === target;
      } catch {
        return false;
      }
    });
    if (matches.length !== 1)
      throw new Error(
        `${path}: expected exactly one ${target} upstream, found ${matches.length}`,
      );
    const array = matches[0]!;
    const close = array.getEnd() - 1;
    const lineStart = result.lastIndexOf("\n", close - 1) + 1;
    if (result[close] !== "]" || !/^[ \t]*$/.test(result.slice(lineStart, close)))
      throw new Error(
        `${path}: the closing bracket of ${target} must be on its own line`,
      );
    const last = array.elements.at(-1);
    const comma = last && !array.elements.hasTrailingComma ? last.end : -1;
    result =
      comma < 0
        ? result.slice(0, lineStart) + texts.join("") + result.slice(lineStart)
        : `${result.slice(0, comma)},${result.slice(comma, lineStart)}${texts.join("")}${result.slice(lineStart)}`;
  }
  return result;
}

export function signature(files: Files, slug: string): string {
  return JSON.stringify(
    [...files]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([path, file]) => [
        path,
        file.mode,
        shared.includes(path)
          ? entryBytes(file.bytes.toString(), path, slug)
          : file.bytes.toString("base64"),
      ]),
  );
}
